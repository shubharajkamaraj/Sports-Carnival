export function getStaticPlayer(id: number) {
  return players.find((player) => player.id === id);
}

export function getStaticPlayers(ids: number[]) {
  return ids
    .map((id) => getStaticPlayer(id))
    .filter(
      (player): player is StaticPlayer =>
        Boolean(player)
    );
}